import { globSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { projectFiles, projectSlices } from 'archunit';
import { describe, expect, it } from 'vitest';

const ROOT_DIRECTORY = path.join(import.meta.dirname, '..');
const ROOT_TSCONFIG_PATH = path.join(ROOT_DIRECTORY, 'tsconfig.json');

// Every way raw data enters the process. Only an anti-corruption layer, an acl/ folder, may use
// them: it parses that data with Zod into domain types (ADR-0005).
const RAW_DATA_ACCESS_LIST = [
  {
    name: 'the Prisma client',
    pattern: /['"](?:@prisma\/|[^'"]*\/generated\/)/,
    exampleList: ["import { PrismaClient } from '#/workspace/generated/client.ts';"],
  },
  { name: 'SQLite', pattern: /['"]node:sqlite['"]/, exampleList: ["import { DatabaseSync } from 'node:sqlite';"] },
  { name: 'HTTP', pattern: /\bfetch\(/, exampleList: ["await fetch('https://example.org');"] },
  // Any use of the file system, read or write, goes through its module: matching the module rather
  // than each function also catches the one nobody listed
  {
    name: 'the file system',
    pattern: /['"](?:node:)?fs(?:\/promises)?['"]/,
    exampleList: [
      "import { readFileSync } from 'node:fs';",
      "import { rmSync } from 'node:fs';",
      "import { unlink } from 'node:fs/promises';",
      "import fs from 'fs';\nfs.writeFileSync('a', 'b');",
      "import * as fs from 'fs/promises';",
      "const fs = await import('node:fs');",
      "const fs = process.getBuiltinModule('node:fs');",
    ],
  },
  { name: 'JSON parsing', pattern: /\bJSON\.parse\b/, exampleList: ["JSON.parse('{}');"] },
  {
    name: 'a child process',
    pattern: /['"]node:child_process['"]/,
    exampleList: ["import { execFileSync } from 'node:child_process';"],
  },
  { name: 'the environment', pattern: /\bprocess\.env\b/, exampleList: ['process.env.TOKEN;'] },
];

// Each folder of src/modules is a module. A diagram without any arrow turns every dependency
// between two modules into a violation (ADR-0003).
function findCrossModuleImports(tsconfigPath: string) {
  return projectSlices(tsconfigPath)
    .definedBy('src/modules/(**)/')
    .should()
    .adhereToDiagram('@startuml\n@enduml')
    .check();
}

// The CLI, the front and the worker only relay to the actions, so no business rule lives in them
// (ADR-0003)
const RELAY_LIST = [
  { folder: 'cli', filePath: 'src/cli/jf.ts' },
  { folder: 'web', filePath: 'src/web/routes/offres.tsx' },
  { folder: 'worker', filePath: 'src/worker/worker.ts' },
];

function findActionsBypassedBy(folder: string, tsconfigPath: string) {
  return projectFiles(tsconfigPath)
    .inFolder(`src/${folder}/**`)
    .shouldNot()
    .dependOnFiles()
    .inPath(new RegExp(`^src/(?!actions/|${folder}/)`))
    .check();
}

// The application lives in src/; the tests and the client generated by Prisma handle raw data on
// purpose. archunit's adhereTo reads each file relative to the working directory, so in a fixture
// project it sees empty files: the files are read here instead.
function findRawDataOutsideAcl(projectDirectory: string): string[] {
  const filePathList = globSync('src/**/*.{ts,tsx}', {
    cwd: projectDirectory,
    exclude: ['**/acl/**', '**/*.test.{ts,tsx}', 'src/workspace/generated/**'],
  });
  return filePathList.flatMap((filePath) => {
    const content = readFileSync(path.join(projectDirectory, filePath), 'utf8');
    return RAW_DATA_ACCESS_LIST.filter(({ pattern }) => pattern.test(content)).map(
      ({ name }) => `${filePath} uses ${name}`,
    );
  });
}

// Only the worker runs jobs, in its own process: run by the front, a session would stop at each
// restart of the front, and fail the worker's running job at its start (ADR-0003)
function findJobsRunOutsideWorker(projectDirectory: string): string[] {
  const filePathList = globSync('src/**/*.{ts,tsx}', {
    cwd: projectDirectory,
    exclude: ['src/actions/**', 'src/worker/**', '**/*.test.{ts,tsx}'],
  });
  return filePathList.filter((filePath) =>
    /\b(?:runQueuedJobs|failInterruptedJobs)\b/.test(readFileSync(path.join(projectDirectory, filePath), 'utf8')),
  );
}

// The families of interchangeable modules, each module in src/modules/<famille>-<nom>/ (ADR-0010).
// source-import is no Source a Veille chooses but the import of a Fiche de poste by hand: an
// ordinary module, out of the family.
const FAMILY_LIST = ['notification', 'source'];
const ORDINARY_MODULE_SET = new Set(['source-import']);

// The one file that imports the modules of a family, and so names them
const MODULE_REGISTRY_PATH = 'src/actions/modules.ts';

// A name in any spelling: kebab, Pascal, camel, snake, with spaces, whatever the case. The match
// stands on word edges, a camelCase hump included, so « rehypePlugins » never names pep.
function spellingPatternOf(moduleName: string): RegExp {
  return new RegExp(moduleName.replaceAll('-', '[-_ ]?'), 'gi');
}

function isWordEdge(before: string | undefined, after: string | undefined): boolean {
  const isOutsideWord =
    before === undefined || after === undefined || !/[a-z0-9]/i.test(before) || !/[a-z0-9]/i.test(after);
  return isOutsideWord || (/[a-z0-9]/.test(before) && /[A-Z]/.test(after));
}

function isNamingModule(content: string, moduleName: string): boolean {
  const matchList = content.matchAll(spellingPatternOf(moduleName));
  for (const { 0: match, index } of matchList) {
    if (isWordEdge(content[index - 1], match[0]) && isWordEdge(match.at(-1), content[index + match.length])) {
      return true;
    }
  }
  return false;
}

// The name of an interchangeable module appears only in its own folder and in the registry: adding
// one is a folder and a line of registry, without migration, action or screen (ADR-0010)
function findModuleNamesOutsideTheirFolder(projectDirectory: string): string[] {
  const moduleList = globSync('src/modules/*/', { cwd: projectDirectory })
    .map((folder) => path.basename(folder))
    .filter((folder) => !ORDINARY_MODULE_SET.has(folder))
    .map((folder) => ({ folder, family: FAMILY_LIST.find((familyName) => folder.startsWith(`${familyName}-`)) }))
    .filter(({ family }) => family !== undefined)
    .map(({ folder, family = '' }) => ({ folder, name: folder.slice(family.length + 1) }));
  const filePathList = [
    ...globSync('src/**/*.{ts,tsx,css}', {
      cwd: projectDirectory,
      exclude: ['**/*.test.{ts,tsx}', 'src/workspace/generated/**', MODULE_REGISTRY_PATH],
    }),
    ...globSync('prisma/schema.prisma', { cwd: projectDirectory }),
  ];
  return filePathList.flatMap((filePath) => {
    const content = readFileSync(path.join(projectDirectory, filePath), 'utf8');
    return moduleList
      .filter(({ folder, name }) => !filePath.startsWith(`src/modules/${folder}/`) && isNamingModule(content, name))
      .map(({ name }) => `${filePath} names ${name}`);
  });
}

// The Source PEP is not a module of the family yet: #60 makes it one, and empties this list
const KNOWN_SOURCE_LEAK_LIST = [
  'src/actions/context.ts names pep',
  'src/actions/detect.ts names pep',
  'src/domain/index.ts names pep',
  'src/geo/city.ts names pep',
  'src/modules/source-import/acl/extraction.ts names pep',
  'src/workspace/acl/config.ts names pep',
];

function createProject(fileContentByPath: Record<string, string>): string {
  const projectDirectory = mkdtempSync(path.join(tmpdir(), 'job-finder-architecture-'));
  const tsconfigPath = path.join(projectDirectory, 'tsconfig.json');
  writeFileSync(tsconfigPath, JSON.stringify({ extends: ROOT_TSCONFIG_PATH, include: ['src'] }));
  for (const [filePath, content] of Object.entries(fileContentByPath)) {
    mkdirSync(path.dirname(path.join(projectDirectory, filePath)), { recursive: true });
    writeFileSync(path.join(projectDirectory, filePath), content);
  }
  return tsconfigPath;
}

describe('architecture', () => {
  it('catches a module importing another module', async () => {
    const tsconfigPath = createProject({
      'src/modules/lettre/index.ts':
        "import { recherche } from '#/modules/recherche/index.ts';\nexport const lettre = recherche;\n",
      'src/modules/recherche/index.ts': 'export const recherche = 1;\n',
    });

    expect(await findCrossModuleImports(tsconfigPath)).toHaveLength(1);
  });

  it('has no module importing another module', async () => {
    expect(await findCrossModuleImports(ROOT_TSCONFIG_PATH)).toEqual([]);
  });

  it.each(RELAY_LIST)('catches the $folder reaching a feature without the actions', async ({ folder, filePath }) => {
    const tsconfigPath = createProject({
      [filePath]: "import { openWorkspace } from '#/workspace/index.ts';\nexport const relay = openWorkspace;\n",
      'src/workspace/index.ts': 'export const openWorkspace = 1;\n',
    });

    expect(await findActionsBypassedBy(folder, tsconfigPath)).toHaveLength(1);
  });

  it.each(RELAY_LIST)('lets the $folder reach the features only through the actions', async ({ folder }) => {
    expect(await findActionsBypassedBy(folder, ROOT_TSCONFIG_PATH)).toEqual([]);
  });

  it('catches raw data used outside an anti-corruption layer', () => {
    const exampleList = RAW_DATA_ACCESS_LIST.flatMap(({ name, exampleList: accessExampleList }) =>
      accessExampleList.map((example) => ({ name, example })),
    );
    const fileContentByPath = Object.fromEntries(
      exampleList.flatMap(({ example }, index) => [
        [`src/offres/raw-${String(index)}.ts`, example],
        [`src/offres/acl/raw-${String(index)}.ts`, example],
      ]),
    );
    const projectDirectory = path.dirname(createProject(fileContentByPath));

    expect(new Set(findRawDataOutsideAcl(projectDirectory))).toEqual(
      new Set(exampleList.map(({ name }, index) => `src/offres/raw-${String(index)}.ts uses ${name}`)),
    );
  });

  it('uses raw data only in an anti-corruption layer', () => {
    expect(findRawDataOutsideAcl(ROOT_DIRECTORY)).toEqual([]);
  });

  it('catches the front running the queued jobs', () => {
    const projectDirectory = path.dirname(
      createProject({ 'src/web/routes/offres.tsx': 'export const run = (actions) => actions.runQueuedJobs();\n' }),
    );

    expect(findJobsRunOutsideWorker(projectDirectory)).toEqual(['src/web/routes/offres.tsx']);
  });

  it('runs the queued jobs only in the worker', () => {
    expect(findJobsRunOutsideWorker(ROOT_DIRECTORY)).toEqual([]);
  });

  it.each([
    { spelling: 'HomeAssistant', content: 'export const channel = HomeAssistant;\n' },
    { spelling: 'homeAssistant', content: 'export const channel = homeAssistant;\n' },
    { spelling: 'home-assistant', content: "export const channel = 'home-assistant';\n" },
    { spelling: 'HOME_ASSISTANT', content: 'export const channel = HOME_ASSISTANT;\n' },
    { spelling: 'Home Assistant', content: '// Pushes to the phone through Home Assistant\n' },
  ])('catches the front naming a notification module as $spelling', ({ content }) => {
    const projectDirectory = path.dirname(
      createProject({
        'src/modules/notification-home-assistant/index.ts': 'export const homeAssistant = 1;\n',
        'src/actions/modules.ts': "import { homeAssistant } from '#/modules/notification-home-assistant/index.ts';\n",
        'src/web/routes/profil.tsx': content,
      }),
    );

    expect(findModuleNamesOutsideTheirFolder(projectDirectory)).toEqual([
      'src/web/routes/profil.tsx names home-assistant',
    ]);
  });

  it('catches a table of its own for a notification module', () => {
    const projectDirectory = path.dirname(
      createProject({
        'src/modules/notification-telegram/index.ts': 'export const telegram = 1;\n',
        'prisma/schema.prisma': 'model ConnexionTelegram {\n  candidatId String @id\n  botToken String\n}\n',
      }),
    );

    expect(findModuleNamesOutsideTheirFolder(projectDirectory)).toEqual(['prisma/schema.prisma names telegram']);
  });

  it('lets pass a word that merely contains a module name, and the ordinary modules', () => {
    const projectDirectory = path.dirname(
      createProject({
        'src/modules/source-pep/index.ts': 'export const pep = 1;\n',
        'src/modules/source-import/index.ts': 'export const fiche = 1;\n',
        'src/web/components/markdown.tsx': "import { a } from './a.ts';\nexport const rehypePlugins = [a];\n",
      }),
    );

    expect(findModuleNamesOutsideTheirFolder(projectDirectory)).toEqual([]);
  });

  it('names an interchangeable module only in its folder and in the registry', () => {
    expect(findModuleNamesOutsideTheirFolder(ROOT_DIRECTORY).toSorted((a, b) => a.localeCompare(b))).toEqual(
      KNOWN_SOURCE_LEAK_LIST,
    );
  });

  // The client generated by Prisma has cycles of its own, out of our hands
  it('has no import cycle', async () => {
    const rule = projectFiles(ROOT_TSCONFIG_PATH)
      .inPath(/^src\/(?!workspace\/generated\/)/)
      .should()
      .haveNoCycles();

    expect(await rule.check()).toEqual([]);
  });
});
